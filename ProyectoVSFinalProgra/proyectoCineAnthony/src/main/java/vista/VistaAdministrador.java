    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
    int filaSeleccionada = tablaPeliculas.getSelectedRow();
    
    if (filaSeleccionada == -1) {
        JOptionPane.showMessageDialog(this, "Por favor, selecciona un elemento de la tabla para eliminar.", "Aviso", JOptionPane.WARNING_MESSAGE);
        return;
    }
    
    String seccionActual = cmbSeccionAdmin.getSelectedItem().toString();
    int idSeleccionado = Integer.parseInt(tablaPeliculas.getValueAt(filaSeleccionada, 0).toString());
    
    int confirmacion = JOptionPane.showConfirmDialog(
        this, "¿Estás seguro de que deseas eliminar este elemento?", "Confirmar Eliminación", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE
    );
    
    if (confirmacion == JOptionPane.YES_OPTION) {
        boolean eliminado = controlador.eliminarElementoPorSeccion(seccionActual, idSeleccionado);
        
        if (eliminado) {
            controlador.cambiarVistaTabla(seccionActual, tablaPeliculas);
            JOptionPane.showMessageDialog(this, "Elemento eliminado con éxito.");
            
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo eliminar el elemento del archivo.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnConfigurarContraseñaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfigurarContraseñaActionPerformed
        //se crea un panel para pedir la nueva
    JPanel panelDialogo = new JPanel(new java.awt.GridLayout(2, 1, 5, 5));
    JLabel etiqueta = new JLabel("Configura una nueva contraseña de administrador:");
    JPasswordField campoPassword = new JPasswordField();
    
    panelDialogo.add(etiqueta);
    panelDialogo.add(campoPassword);
    
    //se pide confirmacion para cambiar contraseña
    int resultado = JOptionPane.showConfirmDialog(
        this, 
        panelDialogo, 
        "Configurar Contraseña", 
        JOptionPane.OK_CANCEL_OPTION, 
        JOptionPane.PLAIN_MESSAGE
    );
    
    // si selecciono ok
    if (resultado == JOptionPane.OK_OPTION) {
        String nuevaPass = new String(campoPassword.getPassword()).trim();
        
        if (nuevaPass.isEmpty()) {
            JOptionPane.showMessageDialog(
                this, 
                "La contraseña no puede estar vacía.", 
                "Error", 
                JOptionPane.ERROR_MESSAGE
            );
            return;
        }
        
        //se guarda la contraseña que se ingreso
        VistaAdministrador.setPasswordAdmin(nuevaPass);
        
        JOptionPane.showMessageDialog(
            this, 
            "¡Contraseña configurada con éxito! Usela la próxima vez que ingrese.", 
            "Guardado", 
            JOptionPane.INFORMATION_MESSAGE
        );
    }
    }//GEN-LAST:event_btnConfigurarContraseñaActionPerformed

