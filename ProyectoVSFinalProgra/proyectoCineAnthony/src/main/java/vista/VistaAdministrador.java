    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
            int filaSeleccionada = tablaPeliculas.getSelectedRow();
    if (filaSeleccionada == -1) {
        JOptionPane.showMessageDialog(this, "Por favor, selecciona un elemento de la tabla para modificar.", "Aviso", JOptionPane.WARNING_MESSAGE);
        return;
    }
    
    int idSeleccionado = Integer.parseInt(tablaPeliculas.getValueAt(filaSeleccionada, 0).toString());
    String seccionActual = cmbSeccionAdmin.getSelectedItem().toString();

    switch (seccionActual) {
        case "Peliculas": {
            Pelicula p = controlador.buscarPeliculaPorId(idSeleccionado);
            if (p == null) return;
            
            JTextField txtTitulo = new JTextField(p.getTitulo());
            JTextField txtSinopsis = new JTextField(p.getSipnopsis());
            JTextField txtGenero = new JTextField(p.getGenero());
            JTextField txtDuracion = new JTextField(String.valueOf(p.getDuracion()));
            JTextField txtClasificacion = new JTextField(p.getClasificacion());
            JTextField txtRutaImagen = new JTextField(controlador.limpiarRutaImagen(p.getRutaImagen()));
            JTextField txtPrecio = new JTextField(String.valueOf(p.getPrecio()));
            
            Object[] formulario = {
                "Título:", txtTitulo, "Sinopsis:", txtSinopsis, "Género:", txtGenero,
                "Duración (min):", txtDuracion, "Clasificación:", txtClasificacion,
                "Nombre Imagen:", txtRutaImagen, "Precio ($):", txtPrecio
            };
            
            if (JOptionPane.showConfirmDialog(this, formulario, "Modificar Película", JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE) == JOptionPane.OK_OPTION) {
                try {
                    boolean actualizado = controlador.actualizarPelicula(
                        idSeleccionado, txtTitulo.getText().trim(), txtSinopsis.getText().trim(),
                        txtGenero.getText().trim(), Integer.parseInt(txtDuracion.getText().trim()),
                        txtClasificacion.getText().trim(), txtRutaImagen.getText().trim(),
                        Double.parseDouble(txtPrecio.getText().trim())
                    );
                    if (actualizado) {
                        controlador.cambiarVistaTabla("Peliculas", tablaPeliculas);
                        JOptionPane.showMessageDialog(this, "¡Película modificada con éxito!");
                    }
                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(this, "Verifica que los campos numéricos sean correctos.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
            break;
        }
        case "Salas": {
            String nombreActual = tablaPeliculas.getValueAt(filaSeleccionada, 1).toString();
            String capacidadActual = tablaPeliculas.getValueAt(filaSeleccionada, 2).toString();

            JTextField txtNombre = new JTextField(nombreActual);
            JTextField txtCapacidad = new JTextField(capacidadActual);
            
            Object[] formulario = {"Nombre Sala:", txtNombre, "Capacidad:", txtCapacidad};
            if (JOptionPane.showConfirmDialog(this, formulario, "Modificar Sala", JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE) == JOptionPane.OK_OPTION) {
                try {
                    controlador.editarSala(idSeleccionado, txtNombre.getText().trim(), Integer.parseInt(txtCapacidad.getText().trim()));
                    controlador.cambiarVistaTabla("Salas", tablaPeliculas);
                    JOptionPane.showMessageDialog(this, "¡Sala modificada con éxito!");
                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(this, "Verifica que la capacidad sea un número válido.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
            break;
        }
        case "Funciones": {
            //se coge el id 
            int idFuncion = Integer.parseInt(tablaPeliculas.getValueAt(filaSeleccionada, 0).toString());

            //buscamos la funcion con el id
            Funcion funcionActual = null;
            for (Funcion f : controlador.obtenerListaFunciones()) {
                if (f.getIdFuncion() == idFuncion) {
                    funcionActual = f;
                    break;
                }
            }

            if (funcionActual == null) {
                JOptionPane.showMessageDialog(this, "No se encontró la función seleccionada.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            //se cargan los datos
            JTextField txtIdPeli = new JTextField(String.valueOf(funcionActual.getPelicula().getId()));
            JTextField txtIdSala = new JTextField(String.valueOf(funcionActual.getSala().getIdSala()));
            JTextField txtHorario = new JTextField(funcionActual.getHorario());
            
            Object[] formulario = {"ID Película:", txtIdPeli, "ID Sala:", txtIdSala, "Horario:", txtHorario};
            
            if (JOptionPane.showConfirmDialog(this, formulario, "Modificar Función", JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE) == JOptionPane.OK_OPTION) {
                try {
                    controlador.editarFuncion(
                        idFuncion, 
                        Integer.parseInt(txtIdPeli.getText().trim()), 
                        Integer.parseInt(txtIdSala.getText().trim()), 
                        txtHorario.getText().trim()
                    );
                    controlador.cambiarVistaTabla("Funciones", tablaPeliculas);
                    JOptionPane.showMessageDialog(this, "¡Función modificada con éxito!");
                } catch (NumberFormatException e) {
                    JOptionPane.showMessageDialog(this, "Verifica que los IDs sean numéricos.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
            break;
        }
    }
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnVerVentasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerVentasActionPerformed
                //instanciar boletosdao
            modelo.dao.BoletoDAO daoBoletos = new modelo.dao.BoletoDAO();
            List<modelo.entidad.Boleto> listaBoletos = daoBoletos.obtenerBoletos();

            //s no hay ventas registradas se muestra mensaje de que esta vacio
            if (listaBoletos == null || listaBoletos.isEmpty()) {
                JOptionPane.showMessageDialog(
                    this, 
                    "No hay boletos vendidos registrados todavía.", 
                    "Reporte de Ventas", 
                    JOptionPane.INFORMATION_MESSAGE
                );
                return;
            }

            //se muestra un cuador de dialogo para mostrar todas las entradas
            StringBuilder resumen = new StringBuilder("---ENTRADAS VENDIDAS---\n\n");
            for (modelo.entidad.Boleto b : listaBoletos) {
                resumen.append("Película: ").append(b.getPelicula())
                       .append(" | Asientos: ").append(b.getAsientos())
                       .append(" | Total: $").append(b.getTotal())
                       .append("\n----------------------------------------------------------------------------------------------\n");
            }

            //se muestra el cuadro de dialogo
            JTextArea textArea = new JTextArea(resumen.toString(), 15, 40);
            textArea.setEditable(false);
            JScrollPane scrollPane = new JScrollPane(textArea);

            JOptionPane.showMessageDialog(
                this, 
                scrollPane, 
                "Boletos vendidos", 
                javax.swing.JOptionPane.PLAIN_MESSAGE
            );
    }//GEN-LAST:event_btnVerVentasActionPerformed

