    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
    //se crea el cuadro para la contraseña
    JPasswordField pwdField = new JPasswordField();
    
    //se crea el cuadro
    Object[] mensaje = {
        "Por favor, ingresa la contraseña de administrador:", 
        pwdField
    };
    
    //se muestra el cuadro
    int opcion = javax.swing.JOptionPane.showConfirmDialog(
        this, 
        mensaje, 
        "Acceso de Administrador", 
        JOptionPane.OK_CANCEL_OPTION, 
        JOptionPane.PLAIN_MESSAGE
    );
    
    //si se presiona ok
    if (opcion == javax.swing.JOptionPane.OK_OPTION) {
        String passwordIngresada = new String(pwdField.getPassword());
        
        //se verifica si la contraseña es correcta
        if (passwordIngresada.equals(VistaAdministrador.getPasswordAdmin())) {
            
            //se crea el cuadro de dialogo
            JOptionPane optionPane = new JOptionPane(
                "¡Bienvenido, Administrador!", 
                JOptionPane.INFORMATION_MESSAGE
            );
            
            JDialog dialog = optionPane.createDialog(this, "Acceso Exitoso");
            
            // Temporizador para cerrarlo solo el tiempo esta en microsegundos
            Timer timer = new javax.swing.Timer(700, new ActionListener() {
                @Override
                public void actionPerformed(java.awt.event.ActionEvent e) {
                    dialog.dispose();
                }
            });
            timer.setRepeats(false);
            timer.start();
            
            dialog.setVisible(true);
            
            // se abre la ventana del admin
            VistaAdministrador ventanaAdmin = new VistaAdministrador();
            ventanaAdmin.setLocationRelativeTo(null);
            ventanaAdmin.setVisible(true);
            
            // se cierra la ventana actual
            this.dispose();
            
        } else {
            //si la contraseña es incorrecta
            JOptionPane.showMessageDialog(
                this, 
                "Contraseña incorrecta.", 
                "Error de Acceso", 
                JOptionPane.ERROR_MESSAGE
            );
        }
    }
    }//GEN-LAST:event_btnIngresarActionPerformed

    public void cambiarPantalla(String nombreCard) {
            CardLayout cl = (CardLayout) contenedorPrincipal.getLayout();
        cl.show(contenedorPrincipal, nombreCard);

        //si se regresa a la cartelera se limpian los datos de las pantallas
        if ("pantallaCartelera".equals(nombreCard)) {
            limpiarPantallaDetalle();
        }

        btnRegresar.setVisible(controladorNavegacion.debeMostrarBotonRegresar(nombreCard));
        btnCartelera.setVisible(!"pantallaCartelera".equals(nombreCard));

    }
    public void limpiarPantallaDetalle() {
        vistaDetalles1.limpiarFormularioPelicula();
        vistaSeleccionAsientos1.reiniciarColoresYEstadosBotones();
}

