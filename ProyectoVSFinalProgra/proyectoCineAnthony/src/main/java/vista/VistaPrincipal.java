    private void btnRegresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegresarActionPerformed
        //encargamos la navegacion al controlador
        String siguientePantalla = controladorNavegacion.procesarRetroceso(contenedorPrincipal);
        
        CardLayout cl = (CardLayout) contenedorPrincipal.getLayout();
        cl.show(contenedorPrincipal, siguientePantalla);

        // Si se regresa a la cartelera se limpian los datos
        if ("pantallaCartelera".equals(siguientePantalla)) {
            limpiarPantallaDetalle();
        }
        //control de visibilidad d botones
        btnRegresar.setVisible(controladorNavegacion.debeMostrarBotonRegresar(siguientePantalla));
        btnCartelera.setVisible(!"pantallaCartelera".equals(siguientePantalla));
    }//GEN-LAST:event_btnRegresarActionPerformed

